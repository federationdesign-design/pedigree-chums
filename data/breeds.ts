//                so a breed reads taller here than its KC standard. Reverting to
//                withers figures would silently undo a full external source review.
//   length:      estimated nose-to-rump, tail excluded (not a formal KC measurement).
//   weight:      typical adult range, Royal Kennel Club standards where published;
//                designer crosses have wider ranges and lower confidence.
